# --- nested shapes ------------------------------------------------------------------------------


class _Nested(BaseModel):
    model_config = ConfigDict(extra="forbid")


# The machine-readable form of the two-file rule (docs/tool-surface.md#9-bsdf), computed from the
# parsed basis alone by `rad_core.bsdf.suitable_for`. R810 moved the pointer out and added that a
# Klems file's `three_phase: true` does not check the full basis: `window_group_tool._basis_refusal`
# keys `BSDF_BASIS_MISMATCH` on the declared basis name containing "klems full".
class SuitableForView(_Nested):
    """Which methods this file's basis can be used in, decided from the basis alone.

    `three_phase` is true for a Klems file and false for a tensor tree, which the `genBSDF` man page
    says *"does not work in the matrix formulation of the daylight coefficient method"*.
    `five_phase_direct` (the five-phase direct-sun term) is the reverse, and `rendering` is always
    true. `three_phase: true` does not check which Klems basis: binding the file for the 3-phase
    chain with `window_group(action="assign_bsdf")` also needs `basis_name` to name the full Klems
    basis, or it is refused with `BSDF_BASIS_MISMATCH`.
    """

    three_phase: bool
    five_phase_direct: bool
    rendering: bool


class ComponentView(_Nested):
    """One `WavelengthDataBlock` of the file, in file order.

    `direction` is the file's own `WavelengthDataDirection` text, such as `"Transmission Front"` or
    `"Reflection Back"`; a block without one is not listed. `scattering_data_type` is the block's
    `ScatteringDataType` text (for example `"BTDF"`), `null` when the block has none.
    """

    direction: str
    scattering_data_type: str | None = None


# Deliberately separate from the parsed fields rather than merged into them: this is a *second*
# opinion from a binary, and merging it would hide which of the two established a given fact. The
# point of check 5.3 is that the pure parser and `checkBSDF` agree; a shape that cannot express
# disagreement cannot report it. R810 moved this out and added what each field holds
# (`rad_engine.bsdf.check_bsdf`) and that a rejected file carries no advisory code
# (`_file_advisories`' own comment: the register allocates nothing for it).
class CheckView(_Nested):
    """What `checkBSDF` itself reported about the file, on `action="validate"` only.

    A second opinion beside the parsed fields, not merged into them. `ok` is true when `checkBSDF`
    exited without error. No advisory code reports a rejection: `ok: false` is the only sign.
    `basis_type`, `has_geometry` and `colour` are its `Type`, `Has Geometry` and `Color` lines,
    `null` when it printed none. `components` names the components it found data for, in its own
    spelling (`"Interior Refl"`, `"Exterior Refl"`, `"Int->Ext Trans"`, `"Ext->Int Trans"`).
    """

    ok: bool
    basis_type: str | None = None
    has_geometry: bool | None = None
    colour: bool | None = None
    components: list[str]


