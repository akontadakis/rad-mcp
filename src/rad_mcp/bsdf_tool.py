class BSDFBase(RadResult):
    """What every bsdf-shaped answer carries. Also the union schema's shared base."""

    project: str
    root: str


# The shape docs/tool-surface.md §9 publishes. One branch for all three actions because they report
# the same facts about the same file and differ only in how the file came to be and whether
# `checkBSDF` was consulted -- the consolidation `rad_mcp.weather_tool.WeatherFile` makes for
# `load`/`describe`. R810 moved this out and lifted the field notes on `bins` and `input_id` (which
# never reached the wire), and added `reciprocity_averaged` always null (`rad_core.bsdf.parse_bsdf`;
# `BSDFFile.reciprocity_averaged` gives the reason) and the tensor4 default (`_basis_of`).
class BSDFInspected(BSDFBase):
    """A BSDF XML's structure, from `bsdf(action="inspect")`, `"validate"` or `"generate"`.

    `path` is the file read, or on `generate` the XML written into the project's `05_bsdf/`. The
    structural fields are read from that file. `basis` is `"klems"` when the file carries
    angle-basis blocks; otherwise it is a tensor tree, `"tensor3"` only when the file declares rank
    3, else `"tensor4"`. `bins` is the Klems direction count summed from the file (145 for the full
    basis), `null` for a tensor tree, which has no fixed directions. `basis_name`, `band` and
    `device_type` are the file's `AngleBasisName`, `Wavelength` and `DeviceType` text, `null` when
    absent or empty. `reciprocity_averaged` is always `null`: the XML does not record it, so it is
    unknown, not false.

    `name` and `input_id` are set on `generate`, and when `inspect`/`validate` read a registered
    BSDF by `name`; `null` when a `path` was read (a `path` is used if both are given). `check` is
    set only on `validate`; `argv` (the exact `genBSDF` command line) and `duration_s` (its
    wall-clock time in seconds) only on `generate`.
    """

    action: Literal["inspect", "validate", "generate"]
    path: str
    basis: str
    bins: int | None = None
    """`null` for a tensor tree, which has no fixed direction count -- not `0`, which would read as
    a basis with no directions in it (`rad_core.bsdf.BSDFFile`)."""
    basis_name: str | None = None
    components: list[ComponentView]
    band: str | None = None
    has_geometry: bool
    reciprocity_averaged: bool | None = None
    device_type: str | None = None
    suitable_for: SuitableForView
    name: str | None = None
    input_id: str | None = None
    """Set when the file is registered in the project -- `generate` always, `inspect`/`validate` when
    the caller named a registered input. `null` for a one-off inspection of a path, which registers
    nothing."""
    check: CheckView | None = None
    argv: list[str] | None = None
    """The exact `genBSDF` command line, on `generate`. Published for the same reason the sky's argv
    is: *"the exact command line is returned to the client, so the sky is auditable"*
    (docs/tool-surface.md §10). A BSDF is a device's optical description; being able to read back how
    it was sampled is what makes it reviewable."""
    duration_s: float | None = None


class BSDFListed(BSDFBase):
    """`bsdf(action="list")`: the project's registered BSDFs. No file is opened."""

    bsdf: list[BSDFRow]


# Shallow for the same reason `WeatherRow` is: listing a project's BSDFs should not parse every XML
# in it, and a row reporting `bins` would have to. R810 moved this out and lifted the `path` field
# note (`_publishable`), which never reached the wire.
class BSDFRow(_Nested):
    """One registered BSDF in `bsdf(action="list")`, from the project record only.

    The file is not opened, so nothing here says the XML still exists or parses; `inspect` reads
    it. `path` is `null` when the recorded file lies outside every allowed root, or the record names
    no file; the BSDF is still registered.
    """

    name: str
    input_id: str
    path: str | None = None
    """`null` when the registered path resolves outside every allowed root -- reported rather than
    echoed, and rather than filtered out. The row still exists and the caller needs to see it; a
    missing row would say "there is no such input", which is false
    (`rad_mcp.weather_tool._listed`, the same rule and reasoning)."""


BSDFListed.model_rebuild()

BSDFPayload = BSDFInspected | BSDFListed | Refusal


class BSDFResult(RootModel[BSDFPayload]):
    """`bsdf`'s result: a `BSDFInspected`, a `BSDFListed` on `action="list"`, or a refusal."""

    @classmethod
    def model_json_schema(cls, *args: Any, **kwargs: Any) -> dict[str, Any]:
        return one_of_schema(super().model_json_schema(*args, **kwargs), BSDFBase)


# --- argument checks ----------------------------------------------------------------------------


def _refuse_argument(message: str, *, field: str) -> CallToolResult:
    """`ARGUMENT_OUT_OF_RANGE` with the argument's own name in `field` -- ruling R14's code for an
    argument refused on its face."""
    return refuse(
        message,
        [Advisory(code="ARGUMENT_OUT_OF_RANGE", severity="error", field=field, message=message)],
    )


def _refuse_name(name: str) -> CallToolResult | None:
    if is_legal_name(name):
        return None
    return _refuse_argument(
        name_refusal_reason(
            name, kind="BSDF", examples="'venetian_45', 'clear-glazing', 'blind.closed'"
        ),
        field="name",
    )


# --- the tool ------------------------------------------------------------------------------------


def bsdf(
    action: Annotated[
        Action,
        Field(
            description=(
                "which operation: \"inspect\", \"validate\", \"generate\" or \"list\". The tool "
                "description says what each one does."
            )
        ),
    ],
    project: Annotated[
        str | None,
        Field(
            description=(
                "the project handle. Required for every action -- a generated XML is written into "
                "a project, and a registered input belongs to one."
            )
        ),
    ] = None,
    path: Annotated[
        str | None,
        Field(
            description=(
                "absolute path to a BSDF XML. REQUIRED on \"inspect\" and \"validate\" unless "
                "`name` names a registered input. The file is read, never modified."
            )
        ),
    ] = None,
    name: Annotated[
        str | None,
        Field(
            description=(
                "the BSDF's handle inside the project, and the generated XML's filename. REQUIRED "
                "on \"generate\". 1-64 characters of ASCII letters, digits, underscore, hyphen and "
                "dot."
            )
        ),
    ] = None,
    geometry: Annotated[
        list[str] | None,
        Field(
            description=(
                "absolute paths to the fenestration `.rad` files, REQUIRED on \"generate\". Model "
                "the whole assembly including sills and edges -- `genBSDF` says accuracy is "
                "impaired otherwise."
            )
        ),
    ] = None,
    basis: Annotated[
        Literal["klems", "tensor3", "tensor4"] | None,
        Field(
            description=(
                "\"klems\" (145 fixed directions, for 3-phase), \"tensor3\" or \"tensor4\" "
                "(variable resolution, for 5-phase direct sun and rendering). REQUIRED on "
                "\"generate\" with NO DEFAULT: the two methods need two different files from the "
                "same device, and substituting one would be a physical default invented on your "
                "behalf."
            )
        ),
    ] = None,
    dim: Annotated[
        list[StrictFloat] | None,
        Field(
            description=(
                "six values, `genBSDF -dim Xmin Xmax Ymin Ymax Zmin Zmax`, to override the "
                "geometry's own bounding box. Use when the system is designed to fit a different "
                "opening."
            )
        ),
    ] = None,
    samples: Annotated[
        StrictInt | None,
        Field(
            description=(
                "`genBSDF -c`. Defaults to the basis-dependent floor -- 2000 for Klems, and `10 x "
                "4^resolution` for a tensor tree, which is the man page's own arithmetic. 1 to "
                "2147483647."
            )
        ),
    ] = None,
    resolution: Annotated[
        StrictInt | None,
        Field(
            description=(
                "`genBSDF -t3/-t4` Nlog2, REQUIRED for a tensor basis. 5 gives 32x32 output "
                "regions, 6 gives 64x64 and needs four times the samples for the same accuracy. "
                "Refused with the Klems basis, which does not use it, and outside 2 to 10."
            )
        ),
    ] = None,
    both_sides: Annotated[
        bool,
        Field(
            description=(
                "`+forward +backward`. Default true, which doubles the runtime and is recommended "
                "when rays impinge from either side. False computes backward components only."
            )
        ),
    ] = True,
    colour: Annotated[
        bool,
        Field(
            description=(
                "`+C`, tristimulus colour. Default false, which is `genBSDF`'s own greyscale `-C`."
            )
        ),
    ] = False,
    isotropic: Annotated[
        bool,
        Field(
            description=(
                "assert the system is radially symmetric, permitting `basis=\"tensor3\"` on "
                "geometry that looks anisotropic. Recorded in the artifact's provenance, because a "
                "rank-3 tree of an anisotropic device is fast and wrong with nothing in the output "
                "to say so."
            )
        ),
    ] = False,
    inline_timeout_s: Annotated[
        StrictFloat,
        Field(
            description=(
                "seconds each Radiance step of \"generate\" may run (getbbox, then genBSDF) before "
                "it is killed with its whole process group and the call is refused. Default 1800. "
                "Measured on an 8-core machine: Klems about 400 s, tensor4 at resolution 4 about "
                "680 s; tensor4 at 5 or above needs more. Ignored by the other actions."
            )
        ),
    ] = BSDF_INLINE_TIMEOUT_S,
) -> BSDFResult:
    """Inspect, validate and generate BSDF XML -- the T matrix of the 3-phase method.

    Use it to check a BSDF XML before `window_group(action="assign_bsdf")` binds it to a window
    group, or to generate one from fenestration geometry.

    DESTRUCTIVE ACTIONS: `generate` replaces any regular file at 05_bsdf/<name>.xml, registered or
    not, and registers the new XML as `bsdf_<name>`; the old file is replaced only after genBSDF's
    output is contained and parses.

    A BSDF describes what a glazing or shading device does to light arriving from every direction,
    and the ways it goes wrong are silent. Two matter most. **The basis is not
    interchangeable**: the 3-phase method needs a 145-direction Klems file and the 5-phase method's
    direct-sun term needs a tensor tree, generated by separate runs from the same device -- hand
    either to the other chain and you get a mismatch, not a warning. And **`genBSDF`'s geometry
    preconditions are hard**: the assembly must sit in the negative Z half-space with +Z pointing
    into the room, and violating that yields a valid-looking XML of a device that is not the one you
    modelled. Both are checked here before anything is computed.

    "inspect" reports a file's basis, bins, components and what it is fit for, reading the XML
    only. "validate" does the same and additionally runs `checkBSDF` as an independent second
    opinion. "generate" runs `genBSDF` over your fenestration geometry and registers the result.
    "list" reports the project's registered BSDFs.
    """
    runtime = current()
    try:
        return _dispatch(
            runtime,
            action,
            project=project,
            path=path,
            name=name,
            geometry=geometry,
            basis=basis,
            dim=dim,
            samples=samples,
            resolution=resolution,
            both_sides=both_sides,
            colour=colour,
            isotropic=isotropic,
            inline_timeout_s=inline_timeout_s,
        )
    except SceneInlineCommandError as exc:
        # R754: a geometry file, or a file its `!xform` chain reaches, carries a `!` line Radiance
        # would run through `/bin/sh`. Raised inside `rad_engine.bsdf` before `getbbox` or genBSDF
        # spawns, and shaped with its own code as `run_annual` shapes it: uncaught, it would escape
        # as a raw `ToolError` (check 0.4). `field` is `geometry`, the argument that named the file.
        # `rad_engine.octree.ShellUnsafePathError`, the same code for a geometry *path* genBSDF
        # would put into /bin/sh (R754 fix round 1), carries its own `field`, also `geometry` here.
        logger.info("bsdf(action=%s) refused: %s", action, exc)
        return refuse(
            str(exc),
            [
                Advisory(
                    code="SCENE_INLINE_COMMAND",
                    severity="error",
                    field=getattr(exc, "field", "geometry"),
                    message=str(exc),
                )
            ],
        )
    except BSDFError as exc:
        # `rad_core.bsdf`'s refusals: the bytes are not a BSDF, or the file's own statements about
        # its basis disagree. `code` is `None` there by design -- the register allocates nothing for
        # "these bytes are not a BSDF" -- so the class is assigned here, exactly as
        # `rad_mcp.weather_tool` assigns it for `EPWError`.
        logger.info("bsdf(action=%s) refused: %s", action, exc)
        return _refuse_argument(
            f"{exc} This file cannot be read as a BSDF XML, so nothing about its optical data has "
            "been judged -- supply a different file.",
            field=getattr(exc, "field", None) or "path",
        )
    except BSDFEngineError as exc:
        logger.info("bsdf(action=%s) refused: %s", action, exc)
        code = getattr(exc, "code", None)
        if code is None:
            # No allocated code for "the file would not open" or "a binary could not be run" -- the
            # gap is reported rather than papered over with a code whose definition is untrue of the
            # condition (`rad_mcp.weather_tool`, the same posture).
            return refuse(str(exc))
        return refuse(
            str(exc),
            [
                Advisory(
                    code=code,
                    severity="error",
                    field=getattr(exc, "field", None),
                    message=str(exc),
                )
            ],
        )
    except RadianceNotFound as exc:
        # An install missing `genBSDF`/`genblinds`/`checkBSDF`/`getbbox` -- the four this tool
        # spawns, all registered under the `bsdf` capability in `rad_engine.env`. Reported as a
        # coded refusal rather than by hiding the tool, which docs/tool-surface.md forbids by name:
        # *"hiding `bsdf` when `genBSDF` is missing"* is the tempting design it rules out, because a
        # surface that varies per connection is one a client cannot cache or reason about.
        logger.info("bsdf(action=%s) refused: %s", action, exc)
        return refuse(
            str(exc),
            [Advisory(code="RADIANCE_NOT_FOUND", severity="error", message=str(exc))],
        )
    except RadianceError as exc:
        # A binary ran and failed -- `genBSDF` exiting non-zero because the scene will not compile
        # (an undefined modifier, a geometry file whose material was not passed alongside it), or
        # `getbbox` refusing the geometry. **Uncaught, this escaped as a raw `ToolError`**, which is
        # the uncoded transport failure check 0.4 forbids: the caller gets a JSON-RPC error instead
        # of a result they can read, and the stderr explaining the mistake is lost with it.
        #
        # No advisory code, deliberately: the register allocates none for "a Radiance binary
        # failed", and the failure is the binary's own stderr rather than a condition this server
        # classified. `RadianceError`'s message carries the argv, the exit status and that stderr,
        # which is what makes an uncoded refusal actionable -- the posture
        # `rad_engine.weather.WeatherFileUnreadableError` established and `run_annual` already
        # takes for this exact exception.
        logger.info("bsdf(action=%s) failed: %s", action, exc)
        return refuse(str(exc))
    except (ProjectError, PathOutsideRoot, RootsNotConfigured) as exc:
        logger.info("bsdf(action=%s) refused: %s", action, exc)
        return refuse_engine_error(exc)
    except OSError as exc:
        logger.warning("bsdf(action=%s) failed on the filesystem: %s", action, exc)
        return refuse(
            f"bsdf(action={action!r}) could not complete: {exc}. Nothing about the arguments is "
            "wrong -- the filesystem refused the operation, so this is an environment problem "
            "(permissions, a read-only mount, or a file held open elsewhere)."
        )


def _dispatch(
    runtime: Runtime,
    action: Action,
    *,
    project: str | None,
    path: str | None,
    name: str | None,
    geometry: list[str] | None,
    basis: str | None,
    dim: list[float] | None,
    samples: int | None,
    resolution: int | None,
    both_sides: bool,
    colour: bool,
    isotropic: bool,
    inline_timeout_s: float,
) -> CallToolResult:
    call = f"bsdf(action={action!r})"
    if (refusal := refuse_missing(call, project=project)) is not None:
        return refusal
    assert project is not None

    loaded = runtime.open(project)

    if action == "list":
        return _listed(runtime, loaded)

    if action == "generate":
        return _generate(
            runtime,
            loaded,
            name=name,
            geometry=geometry,
            basis=basis,
            dim=dim,
            samples=samples,
            resolution=resolution,
            both_sides=both_sides,
            colour=colour,
            isotropic=isotropic,
            inline_timeout_s=inline_timeout_s,
        )

    return _read(runtime, loaded, action=action, path=path, name=name)


# --- inspect / validate --------------------------------------------------------------------------


def _read(
    runtime: Runtime,
    loaded: LoadedProject,
    *,
    action: Literal["inspect", "validate"],
    path: str | None,
    name: str | None,
) -> CallToolResult:
    """Read a BSDF XML and report its structure. `validate` also runs `checkBSDF`.

    Either a `path` or a `name` that matches a registered input. A `name` is resolved through the
    manifest and **re-contained before the read**, on the reasoning ruling R46 records for
    `weather(action="describe")`: "it was inside a root when it was registered" is not the claim
    "it is inside a root now", and the gap is reachable without hand-editing -- a project created
    under wider roots, a directory copied between machines, a parent that became a symlink.
    """
    resolved: Path
    record_id: str | None = None
    handle: str | None = None

    if path is not None:
        resolved = contain(path, runtime.roots)
    elif name is not None:
        if (refusal := _refuse_name(name)) is not None:
            return refusal
        record = _record(loaded, name)
        if record is None:
            return _unknown_name(loaded, name, action=action)
        registered = _file_of(record)
        if registered is None:
            return _refuse_argument(
                f"the BSDF input {record.id!r} records no file, so there is nothing to read. "
                "Re-register it with bsdf(action='generate', ...) or name a path directly.",
                field="name",
            )
        resolved = contain(registered, runtime.roots)
        record_id = record.id
        handle = name
    else:
        return _refuse_argument(
            f"bsdf(action={action!r}) needs either a `path` to an XML file or a `name` that matches "
            "a BSDF registered in this project. Neither was given.",
            field="path",
        )

    parsed = inspect_bsdf(resolved)

    check: CheckView | None = None
    if action == "validate":
        report = check_bsdf(discover(), resolved, cwd=resolved.parent)
        check = CheckView(
            ok=report.ok,
            basis_type=report.basis_type,
            has_geometry=report.has_geometry,
            colour=report.colour,
            components=list(report.components),
        )

    return emit(
        _inspected(
            loaded,
            action=action,
            path=resolved,
            parsed=parsed,
            name=handle,
            input_id=record_id,
            check=check,
            advisories=_file_advisories(parsed, check),
        )
    )


# --- generate ------------------------------------------------------------------------------------


def _generate(
    runtime: Runtime,
    loaded: LoadedProject,
    *,
    name: str | None,
    geometry: list[str] | None,
    basis: str | None,
    dim: list[float] | None,
    samples: int | None,
    resolution: int | None,
    both_sides: bool,
    colour: bool,
    isotropic: bool,
    inline_timeout_s: float,
) -> CallToolResult:
    """Run `genBSDF` over the caller's geometry and register the XML.

    **Every refusal here precedes the spawn**, which is what makes check 5.5's "no `genBSDF` process
    was spawned" assertion structural rather than incidental. In order: missing arguments, the name's
    charset, the basis vocabulary, a tensor basis with no resolution, a Klems basis with one (R743),
    a resolution or samples outside its bound (R749), an `inline_timeout_s` outside R704's range
    (R751), a `dim` without six values, path containment for every geometry file, the `!`-line
    scan of the geometry and every file its `!xform` chain can reach, each preceded by a check that
    every geometry path holds only `[A-Za-z0-9._/+-]`, because genBSDF puts the paths into /bin/sh
    command lines (R754, inside `bounding_box_of` before `getbbox`, and again inside
    `generate_bsdf` before genBSDF), the geometry
    preconditions from `rad_core.bsdf`, the containment of the project's BSDF directory, then,
    inside `generate_bsdf` just before genBSDF spawns, a target that exists and is not a regular
    file (R751). Only after all of those does genBSDF run.
    """
    call = "bsdf(action='generate')"
    if (refusal := refuse_missing(call, name=name, geometry=geometry, basis=basis)) is not None:
        return refusal
    assert name is not None and geometry is not None and basis is not None

    if (refusal := _refuse_name(name)) is not None:
        return refusal
    # N-108 (R851): `bsdf_<name>` is also the id `window_group(action="assign_bsdf")` gives state
    # `<state>` of group `<group>` when `name` is `<group>_<state>` (and `<group>_<state>_direct_sun`
    # at `role="direct_sun"`). `register_input` replaces by id, so a generate here replaced that
    # binding's input record (at `role="matrix"`, the input its sealed `tmx` is built from) with no
    # refusal. Only a record this action wrote is replaced (R802); any other is refused before
    # anything runs.
    held = next((r for r in loaded.manifest.inputs if r.id == _INPUT_PREFIX + name), None)
    if held is not None and (
        held.registered_by is None
        or (held.registered_by.tool, held.registered_by.action) != ("bsdf", "generate")
    ):
        writer = (
            f"{held.registered_by.tool}(action={held.registered_by.action!r})"
            if held.registered_by is not None
            else "a call the manifest does not record"
        )
        return _refuse_argument(
            f"name={name!r} would register input {held.id!r}, which {writer} already holds"
            + (" (a window group's BSDF binding: window_group(action='assign_bsdf') joins the "
               "group and state names with '_')" if held.registered_by is not None
               and held.registered_by.tool == "window_group" else "")
            + ". generate replaces only a BSDF it generated itself, so nothing was generated or "
            "recorded. Choose another name.",
            field="name",
        )

    try:
        chosen = Basis(basis)
    except ValueError:
        return _refuse_argument(
            f"basis={basis!r} is not one of 'klems', 'tensor3' or 'tensor4'. There is no default: "
            "the 3-phase method needs a 145-direction Klems file and the 5-phase direct-sun term "
            "needs a tensor tree, and substituting one for the other is a mismatch you would only "
            "discover when the matrices refused to multiply.",
            field="basis",
        )

    if chosen is not Basis.KLEMS and resolution is None:
        return _refuse_argument(
            f"basis={basis!r} needs a `resolution`: -t3/-t4 take the log base 2 of the sampling "
            "resolution in each dimension and genBSDF has no default for it. 5 gives 32x32 output "
            "regions and 6 gives 64x64 -- and 6 needs four times the samples of 5 for the same "
            "accuracy per region.",
            field="resolution",
        )
    if chosen is Basis.KLEMS and resolution is not None:
        return _refuse_argument(
            f"basis={basis!r} takes no `resolution`: genBSDF reads one only for a tensor tree "
            "(-t3/-t4), so a Klems run would ignore it while the project recorded it. Omit it, or "
            'choose basis "tensor3" or "tensor4".',
            field="resolution",
        )

    # R749: before `sample_floor`, whose `10 * 4**resolution` took 10 s at 10**9 and had not
    # finished after 60 s at 10**10, and before anything is recorded. The value is never echoed:
    # Python refuses to turn an integer of more than 4300 digits into text.
    if resolution is not None and not RESOLUTION_MIN <= resolution <= RESOLUTION_MAX:
        return _refuse_argument(
            f"resolution must be an integer from {RESOLUTION_MIN} to {RESOLUTION_MAX}. genBSDF exited with "
            "an error at 1 on both tensor bases when measured, and at 10 the sample floor (10 per output "
            "region) is already 10,485,760 samples for a tensor4 tree and 10,240 for a tensor3 tree.",
            field="resolution",
        )
    if samples is not None and not SAMPLES_MIN <= samples <= SAMPLES_MAX:
        return _refuse_argument(
            f"samples must be an integer from {SAMPLES_MIN} to {SAMPLES_MAX}. genBSDF runs 0 as one sample, "
            "so give 1 for that; it failed at -1.",
            field="samples",
        )
    # R751: the bound is checked with the other argument refusals, before `sample_floor`, the
    # bounding box and any spawn. `refuse_inline_timeout` is the check every tool that takes the
    # argument uses (R704).
    if (refusal := refuse_inline_timeout(inline_timeout_s)) is not None:
        return refusal

    if dim is not None and len(dim) != 6:
        return _refuse_argument(
            f"dim needs exactly six values (Xmin Xmax Ymin Ymax Zmin Zmax), got {len(dim)}.",
            field="dim",
        )

    contained_geometry = tuple(contain(item, runtime.roots) for item in geometry)

    # The floor is `rad_core`'s, never re-derived here. An explicit `samples` below it is honoured
    # and *reported* rather than raised to the floor: silently substituting a sample count would make
    # the published argv disagree with what the caller asked for.
    floor = sample_floor(chosen, resolution)
    effective_samples = samples if samples is not None else floor

    box = _bounding_box(runtime, contained_geometry, timeout=inline_timeout_s)
    precondition = check_generate_geometry(
        box,
        basis=chosen,
        anisotropic=_looks_anisotropic(chosen, contained_geometry),
        isotropic=isotropic,
    )
    if not precondition.ok:
        # `BSDF_GEOMETRY_ORIENTATION` for the half-space and aperture failures, which are geometric;
        # the tensor3 anisotropy refusal is its own allocated code. Both at `error`, both before any
        # spawn -- check 5.5 asserts precisely this ordering.
        return _refuse_precondition(precondition, basis=chosen)

    paths = ProjectPaths(loaded.paths.root)
    target = (paths.root / _BSDF_DIRNAME / f"{name}.xml")

    # **Contained before the write, and this ordering is the whole guard** -- the lesson
    # `rad_mcp.weather_tool._load` records: a check downstream of the syscall it is meant to prevent
    # is a report, not a guard. `resolved_parent_within` covers the intermediate components that
    # `O_NOFOLLOW` cannot, so a directory symlink at `05_bsdf` is refused before `mkdir` traverses it.
    if not resolved_parent_within(target, runtime.roots):
        raise PathOutsideRoot(
            f"the project's BSDF directory {target.parent} resolves outside every allowed root, so "
            f"the XML for {name!r} was not written. Nothing has been changed on disk."
        )

    spec = GenBSDFSpec(
        basis=chosen,
        geometry=contained_geometry,
        samples=effective_samples,
        resolution=resolution,
        both_sides=both_sides,
        colour=colour,
        dim=tuple(dim) if dim is not None else None,  # type: ignore[arg-type]
    )

    # Wall clock across the spawn, so `BSDF_GENERATION_SLOW` reports a measured duration rather than
    # an estimate. `time.monotonic` and not `time.time`: a clock adjustment mid-generation would
    # otherwise produce a negative elapsed time on a 40-minute run.
    started = time.monotonic()
    try:
        staging, result = generate_bsdf(
            discover(), spec, out_path=target, cwd=paths.root, timeout=inline_timeout_s
        )
    except NotARegularFileError:
        # `safe_io`'s own text says "Point `out` at a plain file", and `bsdf` has no `out` argument;
        # the repair here is the XML's name or the occupied path (the wrapper
        # `rad_mcp.geometry_tool._refuse_non_regular` exists for the same reason).
        return refuse(
            f"{str(target)!r} exists and is not a regular file, so bsdf cannot write the XML for "
            f"{name!r} there. Remove whatever occupies that path, or give `name` a different value, "
            "and re-run."
        )
    duration_s = time.monotonic() - started
    # R751 (decision 14): the staging file is contained and parsed *before* it replaces an existing
    # XML, so a run that writes something unparseable keeps the old one. A failure while registering
    # below, after the replace, leaves the new XML with the old record -- the owner accepted that
    # narrower guarantee on 2026-10-02.
    try:
        contain(staging, runtime.roots)
        parsed = inspect_bsdf(staging)
        written = commit_staged(staging, target)
    except BaseException:
        staging.unlink(missing_ok=True)
        raise
    input_id = _INPUT_PREFIX + name
    with runtime.modifying(paths):
        fresh = open_project(paths.root, radiance_version=runtime.launcher.version)
        register_input(
            fresh,
            input_id=input_id,
            kind="bsdf",
            files=[written],
            registered_by=ToolCall(
                tool="bsdf",
                action="generate",
                arguments={
                    "name": name,
                    "basis": chosen.value,
                    "samples": effective_samples,
                    "resolution": resolution,
                    "both_sides": both_sides,
                    "colour": colour,
                    "geometry": [str(item) for item in contained_geometry],
                    # The override goes into provenance because the failure it permits is invisible
                    # in the XML. `rad_core.bsdf.ANISOTROPY_OVERRIDE_REASON` is the recorded reason.
                    **({"isotropic": True} if precondition.isotropy_overridden else {}),
                },
            ),
        )

    advisories = _file_advisories(parsed, None)
    advisories += _generation_advisories(
        chosen,
        resolution=resolution,
        samples=effective_samples,
        floor=floor,
        both_sides=both_sides,
        colour=colour,
        precondition=precondition,
        duration_s=duration_s,
    )

    return emit(
        _inspected(
            loaded,
            action="generate",
            path=written,
            parsed=parsed,
            name=name,
            input_id=input_id,
            check=None,
            advisories=advisories,
            argv=result.argv,
            duration_s=duration_s,
        )
    )


def _bounding_box(runtime: Runtime, geometry: tuple[Path, ...], *, timeout: float | None):
    """The geometry's bounding box, via `getbbox`. Reads the geometry; traces nothing.

    Delegated to `rad_engine.geometry`'s existing reader rather than re-spawned here, so there is one
    place that knows how to ask Radiance for a bounding box.
    """
    # `runtime.launcher` is the job `Launcher` and NOT a `RadianceEnv` -- the two are different
    # objects with different jobs, and passing one where the other is expected is a mistake this
    # module made until it was caught. `discover()` is how every other tool obtains the env
    # (`rad_mcp.annual_tool`).
    return bounding_box_of(discover(), geometry, timeout=timeout)


def _looks_anisotropic(basis: Basis, geometry: tuple[Path, ...]) -> bool:
    """Whether the geometry is anisotropic, which only matters for `tensor3`.

    Answered only when it can change the outcome: for Klems and `tensor4` the question is moot, and
    reading every geometry file to answer a question with no consequence would be work the caller
    pays for and cannot observe.
    """
    if basis is not Basis.TENSOR3:
        return False
    return looks_anisotropic(geometry)


def _refuse_precondition(precondition, *, basis: Basis) -> CallToolResult:
    """Shape the geometry refusals, one advisory per independent reason.

    Two codes, chosen by what the reason is about rather than by which check produced it:
    `BSDF_GEOMETRY_ORIENTATION` for the half-space and aperture failures, and
    `ARGUMENT_OUT_OF_RANGE` for the rank-3 anisotropy refusal. Both `error`.

    **The anisotropy refusal deliberately does *not* carry `BSDF_TENSOR_ISOTROPY_ASSUMED`**, and
    this was a real defect caught by check 2.x's register scan. That code is allocated at **warn**,
    and its register row defines it as *"`-t3` used, which only holds for radially symmetric
    systems"* — a statement about a `-t3` run that **proceeded**. Emitting it at `error` for a
    refusal would have said the opposite of what it means: nothing was assumed, because nothing ran.
    Codes are allocated once with their severity and never repurposed
    (docs/tool-surface.md#advisory-code-register), so the refusal takes ruling R14's
    `ARGUMENT_OUT_OF_RANGE` — the class for an argument refused on its face, which `basis="tensor3"`
    on anisotropic geometry is. `BSDF_TENSOR_ISOTROPY_ASSUMED` is still emitted by this tool, at its
    allocated `warn`, on the path where the caller's `isotropic=True` override makes `-t3`
    genuinely proceed on geometry that looks anisotropic — which is exactly the condition it names.
    """
    advisories = []
    for reason in precondition.reasons:
        if "radial symmetry" in reason:
            advisories.append(
                Advisory(
                    code="ARGUMENT_OUT_OF_RANGE",
                    severity="error",
                    field="basis",
                    message=reason,
                )
            )
        else:
            advisories.append(
                Advisory(
                    code="BSDF_GEOMETRY_ORIENTATION",
                    severity="error",
                    field="geometry",
                    message=reason,
                )
            )
    return refuse(
        "genBSDF's preconditions are not met by this geometry, so nothing was generated and no ray "
        "was traced. " + " ".join(precondition.reasons),
        advisories,
    )


# --- list ----------------------------------------------------------------------------------------


def _listed(runtime: Runtime, loaded: LoadedProject) -> CallToolResult:
    rows = []
    for record in loaded.manifest.inputs:
        if record.kind != "bsdf":
            continue
        rows.append(
            BSDFRow(
                name=_name_of(record.id),
                input_id=record.id,
                path=_publishable(_file_of(record), runtime),
            )
        )
    return emit(
        BSDFListed(project=loaded.paths.name, root=str(loaded.paths.root), bsdf=rows)
    )


def _publishable(path: Path | None, runtime: Runtime) -> str | None:
    """`str(path)` if inside an allowed root, else `None` -- swallowed rather than raised, because
    `list` must keep answering (`rad_mcp.weather_tool._publishable`, same rule)."""
    if path is None:
        return None
    try:
        return str(contain(path, runtime.roots))
    except (PathOutsideRoot, RootsNotConfigured):
        return None


# --- advisories ----------------------------------------------------------------------------------


def _file_advisories(parsed: BSDFFile, check: CheckView | None) -> list[Advisory]:
    """What can be said about a file from its own structure.

    `BSDF_BASIS_MISMATCH` and `BSDF_TENSOR_NOT_FOR_MATRIX` are **not** here -- both are about an
    *assignment* to a chain, which `window_group(action="assign_bsdf")` owns (Phase 6). See the
    module docstring.
    """
    advisories: list[Advisory] = []

    if not parsed.has_back_component:
        advisories.append(
            Advisory(
                code="BSDF_NO_BACK_COMPONENT",
                severity="warn",
                field="path",
                message=(
                    "This file carries no forward (exterior-side) components: its "
                    f"{len(parsed.components)} data block(s) describe the backward direction only. "
                    "genBSDF computes backward components unless +forward is given, and the man page "
                    "recommends both 'when rays will be impinging from either side' -- which is the "
                    "normal case for a window. The missing data is absent rather than zero, so a "
                    "render or matrix using this file has no exterior-side scattering to draw on. "
                    "Regenerate with both_sides=True if rays reach this device from outside."
                ),
            )
        )

    if parsed.is_greyscale:
        advisories.append(
            Advisory(
                code="BSDF_GREYSCALE",
                severity="info",
                field="path",
                message=(
                    f"This BSDF's data is greyscale: its wavelength band is {parsed.band!r} and it "
                    "carries no tristimulus components -- genBSDF's own default, since -C reduces "
                    "all BSDF data to grayscale. That is the right choice for illuminance and "
                    "daylight-factor work, where the photopic conversion happens downstream. "
                    "Regenerate with colour=True only if you need tristimulus data for a "
                    "colour-critical render."
                ),
            )
        )

    # **A file `checkBSDF` rejects carries NO advisory code, and that gap is reported rather than
    # filled.** This branch used to raise `BSDF_BASIS_MISMATCH`, which is wrong: that code's register
    # row is about *"the assigned XML's basis is not the 145-bin Klems full basis the V and D matrices
    # were binned into"* -- a statement about an assignment to a chain, which `validate` performs
    # none of. `checkBSDF` refusing a file is a different condition, and the register allocates
    # nothing for it. Codes are allocated once and never repurposed
    # (docs/tool-surface.md#advisory-code-register), so the finding is carried as `check.ok: false`
    # alone (`CheckView` publishes no `checkBSDF` stdout) -- the same posture `rad_engine.weather`'s
    # code-less refusal takes. A code whose definition is untrue of the condition is worse than no
    # code: callers grep for these.
    return advisories


def _generation_advisories(
    basis: Basis,
    *,
    resolution: int | None,
    samples: int,
    floor: int,
    both_sides: bool,
    colour: bool,
    precondition,
    duration_s: float | None = None,
) -> list[Advisory]:
    """What can be said about how a file was generated, as distinct from what it contains."""
    advisories: list[Advisory] = []

    if samples < floor:
        per_region = samples_per_region(basis, resolution, samples)
        density = (
            f" That is {per_region:.2f} samples per output region"
            if per_region is not None
            else ""
        )
        advisories.append(
            Advisory(
                code="BSDF_SAMPLE_COUNT_LOW",
                severity="warn",
                field="samples",
                message=(
                    f"samples={samples} is below the floor of {floor} for a {basis.value} basis."
                    f"{density}, where the genBSDF man page's own worked example targets 10. The XML "
                    "will be well-formed and its noise will not be visible in it -- an "
                    "under-sampled BSDF is a plausible-looking description of a device that was "
                    "never adequately measured. Raise samples, or lower resolution."
                ),
            )
        )

    if duration_s is not None and duration_s > _SLOW_GENERATION_SECONDS:
        advisories.append(
            Advisory(
                code="BSDF_GENERATION_SLOW",
                severity="info",
                field="basis",
                message=(
                    f"This generation took {duration_s:.0f} s. For reference, measured on an 8-core "
                    "machine: a Klems run at -c 2000 took 90 s backward-only with -n 6, and 401 s "
                    "with both_sides=True, measured running genBSDF directly with the argv this tool "
                    "builds (one process; 464 s through this tool with a tensor generation running "
                    "alongside); a tensor tree "
                    "at -t4 5 -c 10240 took 2504 s (41.7 minutes), backward-only with -n 6. Cost "
                    "scales with the sample count: raising a tensor4 resolution by one needs "
                    "four times the samples for the same accuracy (tensor3, twice), and measured "
                    "time grew faster -- tensor4 took 42 s at resolution 3 and 684 s at 4, "
                    "tensor3 5 s at 5 (one process, both sides, at the sample floor). Generate a "
                    "device's two bases once and reuse the XMLs: a BSDF describes the device, not "
                    "the project."
                ),
            )
        )

    if precondition.isotropy_overridden:
        advisories.append(
            Advisory(
                code="BSDF_TENSOR_ISOTROPY_ASSUMED",
                severity="warn",
                field="isotropic",
                message=(
                    "A rank-3 tensor tree was generated for geometry that looks anisotropic, on your "
                    "explicit isotropic=True assertion. "
                    + " ".join(precondition.overridden_reasons)
                ),
            )
        )

    return advisories


# --- shared shaping ------------------------------------------------------------------------------


def _inspected(
    loaded: LoadedProject,
    *,
    action: Literal["inspect", "validate", "generate"],
    path: Path,
    parsed: BSDFFile,
    name: str | None,
    input_id: str | None,
    check: CheckView | None,
    advisories: list[Advisory],
    argv: list[str] | None = None,
    duration_s: float | None = None,
) -> BSDFInspected:
    return BSDFInspected(
        project=loaded.paths.name,
        root=str(loaded.paths.root),
        action=action,
        path=str(path),
        basis=parsed.basis.value,
        bins=parsed.bins,
        basis_name=parsed.basis_name,
        components=[
            ComponentView(
                direction=component.direction,
                scattering_data_type=component.scattering_data_type,
            )
            for component in parsed.components
        ],
        band=parsed.band,
        has_geometry=parsed.has_geometry,
        reciprocity_averaged=parsed.reciprocity_averaged,
        device_type=parsed.device_type,
        suitable_for=SuitableForView(
            three_phase=parsed.suitable_for.three_phase,
            five_phase_direct=parsed.suitable_for.five_phase_direct,
            rendering=parsed.suitable_for.rendering,
        ),
        name=name,
        input_id=input_id,
        check=check,
        argv=argv,
        duration_s=duration_s,
        advisories=advisories or None,
    )


def _name_of(input_id: str) -> str:
    return input_id[len(_INPUT_PREFIX) :] if input_id.startswith(_INPUT_PREFIX) else input_id


def _record(loaded: LoadedProject, name: str) -> Any | None:
    candidates = {name, _INPUT_PREFIX + name}
    for record in loaded.manifest.inputs:
        if record.kind == "bsdf" and record.id in candidates:
            return record
    return None


def _file_of(record: Any) -> Path | None:
    """The record's XML. `None` rather than an `IndexError` on a record with no files, which is
    reachable through a hand-edited manifest (`rad_mcp.weather_tool._files_of`, same reasoning)."""
    return next((Path(f.path) for f in record.files), None)


def _unknown_name(loaded: LoadedProject, name: str, *, action: str) -> CallToolResult:
    known = sorted(
        _name_of(record.id) for record in loaded.manifest.inputs if record.kind == "bsdf"
    )
    return _refuse_argument(
        f"bsdf(action={action!r}) found no BSDF named {name!r} in project "
        f"{loaded.paths.name!r}. "
        + (f"Registered: {', '.join(known)}." if known else "This project has no BSDF registered.")
        + " Generate one with bsdf(action='generate', ...), or pass `path` to inspect a file "
        "directly.",
        field="name",
    )
