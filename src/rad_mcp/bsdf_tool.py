"""The `bsdf` tool -- docs/tool-surface.md#9-bsdf.

Thin, in the sense CONTEXT.md's Layers table means it: this module validates and contains arguments,
picks the engine call, maps findings onto the wire and shapes the envelope. **No number reported here
is computed here.** `rad_core.bsdf` owns the XML structure, the basis rules, the sample floor and the
`genBSDF` preconditions; `rad_engine.bsdf` owns the argv, the spawns and the `checkBSDF` parse. This
module plumbs.

## The preconditions are checked before a single ray is traced, and that ordering is the check

Check 5.5 asserts `BSDF_GEOMETRY_ORIENTATION` fires *"before any ray is traced -- asserted by
checking no `genBSDF` process was spawned"* (docs/plan.md Phase 5). That is true by construction
here: `_generate` calls `rad_core.bsdf.check_generate_geometry` and returns a refusal on failure
before it reaches `rad_engine.bsdf.generate_bsdf`. The bounding box it checks comes from `getbbox`,
which reads the geometry but traces nothing.

The same ordering serves the caller's wallet rather than only their correctness: on this machine
a Klems generation took 463.6 s through this tool and 400.8 s with genBSDF run directly on the argv
this tool builds, and a backward-only `-t4 5` run 41.7 minutes with `-n 6` (measured -- see
`tests/fixtures/README.md` and the Phase 17 design's M8), so a precondition discovered afterwards
can cost that long spent producing a valid XML of the wrong device.

## `basis` has no default, and that is a physics decision rather than an ergonomic one

The two phases need two files from the same physical device: a Klems XML for the 3-phase terms and a
tensor tree for the accurate direct-sun term, generated by *separate* `genBSDF` runs because
`bsdf2klems` *"might not work well with specular components"* (specs/five-phase-method.md §1.2).
Defaulting `basis` would pick one of those two for a caller who did not know there were two, and the
mismatch is only detectable later, at `window_group(action="assign_bsdf")`, as
`BSDF_BASIS_MISMATCH`. So it is required, the same way `units` is required on
`project(action="create")` (ruling R57): a substituted basis is a physical default invented on the
caller's behalf.

## What `generate` refuses, and what it merely reports

Refused: geometry in the positive Z half-space, a degenerate aperture, and `basis="tensor3"` on
anisotropic geometry -- all three from `rad_core.bsdf`, all three before any spawn. Reported and not
refused: a sample count under the basis-dependent floor (`BSDF_SAMPLE_COUNT_LOW`), greyscale output
(`BSDF_GREYSCALE`), a missing back component (`BSDF_NO_BACK_COMPONENT`) and a slow generation
(`BSDF_GENERATION_SLOW`). The split follows the tool's own spec: an under-sampled XML is still a
file the caller can use and judge, while a wrongly-oriented one is a claim about a different device.

## Three code gaps, all reported rather than filled

`BSDF_BASIS_MISMATCH` (error) is allocated and is **not** emitted here: its register row is about an
assigned XML whose basis is not what the V and D matrices were binned into, and there is no
assignment at this tool -- `window_group(action="assign_bsdf")` owns it (Phase 6). Emitting it here
would require this tool to invent which chain the file is destined for. `suitable_for` is the
machine-readable fact the eventual mismatch is computed *from*, and this tool publishes that.

`BSDF_TENSOR_NOT_FOR_MATRIX` (error) is likewise Phase 6's: it fires when a tensor tree is handed to
a 3-phase chain, which is an assignment. This tool reports `suitable_for.three_phase: false` on
every tensor tree, which is the same fact one step earlier and at `info` rather than `error`, because
inspecting a tensor tree is not itself a mistake.

**And a file `checkBSDF` rejects has no code at all.** The register allocates nothing for "the
validator refused this file", so the finding is carried as `check.ok: false` plus `checkBSDF`'s own
stdout rather than borrowed from a code that means something else -- this branch emitted
`BSDF_BASIS_MISMATCH` until that was caught, which was the same category error as the two above with
the severity happening to match. The gap is the posture
`rad_engine.weather.WeatherFileUnreadableError` established: a refusal with no allocated code carries
its reason as prose and names the argument it is about.
"""

