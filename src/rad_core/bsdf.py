"""BSDF XML structure and `genBSDF` preconditions -- pure, no Radiance, fully unit-testable.

Checks 5.1, 5.2, 5.4, 5.5 and 5.6 (docs/plan.md#phase-5--bsdf). Specified in
docs/tool-surface.md#9-bsdf, which this module implements.

**Layers.** This module reads a BSDF XML's *structure* -- basis, bin count, components, wavelength
band, whether geometry is embedded -- and decides what that structure is fit for. It also holds the
`genBSDF` preconditions, which are geometric facts about a bounding box rather than Radiance
knowledge. `rad_engine.bsdf` owns everything that runs a binary: `checkBSDF`, `genBSDF`,
`genblinds`, `wrapBSDF`, and the argv those need. Nothing here imports either layer, so a basis
mismatch is catchable in a pure test with no Radiance installed
(docs/tool-surface.md#9-bsdf, Layers; `tests/test_purity.py`).

**One numeric reading, and it is the Klems integral (R871).** `klems_rings`,
`klems_transmission_blocks` and `klems_diffuse_transmittance` read a Klems file's `ThetaBounds`
and `ScatteringData` to compute a block's diffuse-diffuse (hemispherical) transmittance, and
`lambertian_klems_text` composes from it the uniform state LM-83's 5 % default stands for. Still
text in and text out: no binary, no file handle.

**Text in, never a path.** `parse_bsdf(text)` takes the XML's text exactly as
`rad_core.weather.parse_epw` takes the EPW's, and for the same reason: the purity guard forbids the
*file handle*, not the format (`tests/test_purity.py`, `QUALIFIED_FILE_IO` -- `json.load` is
forbidden where `json.dumps` is not). So `ElementTree.fromstring` is used and `ElementTree.parse`
is not; the layer above reads the disk.

## The namespace is load-bearing, and getting it wrong finds nothing

A `genBSDF` XML's root is `{http://windows.lbl.gov}WindowElement`, so `root.find("Optical")`
returns `None` on a perfectly valid file -- verified on this machine against a `genBSDF` 6.1a
output (`tests/fixtures/README.md`, "BSDF XML structure"). An un-namespaced parser therefore does
not fail loudly; it reports a file with no basis and no components, which reads as a corrupt device
rather than a bug in the reader. Every lookup here matches on the **local** tag name with the
namespace stripped, which handles the namespaced form, a namespace-less hand-written file, and a
file carrying some other vendor's namespace identically. That is deliberate breadth: the structure
this module reads is the WINDOW6 schema's, and a supplied WINDOW6 file is exactly what
`action="validate"` exists for.

## Basis, and why `bins` is `None` for a tensor tree

A Klems file declares `AngleBasisName` and carries one `AngleBasisBlock` per theta ring, each with
an `nPhis` count. The bin count is the **sum of those counts, read from the file** -- 145 for the
full Klems basis, confirmed against the generated fixture -- and never a constant matched off the
basis name. A file naming itself "LBNL/Klems Full" while carrying blocks that sum to something else
is a file whose own two statements disagree, and reporting the name's implication would hide that.

A tensor tree has no angle basis at all: its data is a variable-resolution tree, not a fixed set of
directions. `bins` is `None` rather than `0`, because `0` reads as a basis with no directions in it
while `None` says the concept does not apply -- the same distinction `rad_mcp.weather_tool`'s `wea`
key documents for `null` versus `""`.

## `suitable_for` is three independent claims, and one of them is a citation

- `three_phase` -- **Klems only.** The man page's NOTES are explicit that the tensor-tree
  representation *"does not work in the matrix formulation of the daylight coefficient method"*
  (verified against `man genBSDF` on this install, Radiance 6.1a). That sentence is what makes
  `three_phase: false` for a tensor tree a citation rather than an inference, and it is why
  `BSDF_TENSOR_NOT_FOR_MATRIX` is an `error` and not a `warn`.
- `five_phase_direct` -- **tensor tree only.** The five-phase method's direct-sun term needs the
  angular precision a 145-direction basis has already averaged away, which is why the two phases
  need two files from the same device, generated by separate `genBSDF` runs
  (specs/five-phase-method.md §1.2).
- `rendering` -- **either.** Both bases are read by the Radiance rendering tools; the tensor tree is
  the one the man page calls *"practical, high-resolution data for use in the Radiance rendering
  programs"*.

`suitable_for` is the machine-readable form of the basis distinction, so it is computed from the
parsed basis and never passed in.

## The `genBSDF` half-space precondition, and the floating-point residue that nearly breaks it

`genBSDF` requires the geometry to *"fit a rectangular profile, whose width is along the X-axis,
height is in the Y-axis, and depth is in the Z-axis. The positive Z-axis points into the room, and
the input geometry should not extend into the room. (I.e., it should not contain any positive Z
values, since the putative emitting surface is assumed to lie at Z=0.)"* -- quoted from
`man genBSDF` on this install. Violating it yields a valid-looking XML of the wrong device, which
is why this is checked before a single ray is traced.

**The tolerance is not decoration and it is not invented.** The man page's own example transform,
`genblinds ... | xform -rz -90 -rx 90`, lands the assembly at a maximum Z of `1.64179e-16` --
measured on this machine, recorded in `tests/fixtures/README.md`. That is the residue of rotating a
zero through two matrices, not geometry in the room. A precondition written as `z_max > 0` refuses
the man page's own worked example, so the check admits a tolerance of one part in a billion of the
assembly's own depth, floored at an absolute epsilon for a degenerate box. Scaled rather than
absolute because the residue scales with the coordinates it came from: a blind modelled in
millimetres carries a thousand times the residue of the same blind in metres, and a fixed epsilon
would be either too tight for one or too loose to catch a real 0.5 mm intrusion in the other.

## Anisotropy is a refusal, and it is decided from the geometry's own shape

`-t3` *"only works in special circumstances, specifically when the system has a high degree of
radial symmetry"*, and the man page says outright: *"do NOT use this option if the system is not in
fact isotropic"*. A rank-3 tree of a venetian blind is fast and wrong, so `basis="tensor3"` on
geometry this module finds anisotropic is refused (docs/tool-surface.md#9-bsdf, Refuses).

What "anisotropic" means here is stated rather than guessed, because the alternative is a heuristic
nobody can predict: a **directional count of distinct parallel surfaces**. Venetian slats are many
polygons stacked along one axis and repeating in none of the others -- radial symmetry about Z is
exactly what that is not. A caller who knows better can say so with `isotropic=True`, which is
honoured and *recorded* rather than silently trusted: the whole point of the refusal is that the
failure is invisible in the output, so the override belongs in the provenance.
"""

