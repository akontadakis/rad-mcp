# --- vocabulary ----------------------------------------------------------------------------------


class Basis(str, Enum):
    """The three bases `bsdf` accepts, named exactly as the tool's `basis` argument spells them.

    A `str` enum so a parsed basis serialises onto the wire as `"klems"` without the protocol layer
    mapping it, the same way `rad_core.method.StateKind` is spelled for `run_annual`.
    """

    KLEMS = "klems"
    TENSOR3 = "tensor3"
    TENSOR4 = "tensor4"


#: The full Klems basis's direction count, and the reference value check 5.1 asserts. Named here as
#: the *expected* sum so a file whose `AngleBasisBlock`s disagree with its own `AngleBasisName` can
#: be reported as inconsistent -- it is never substituted for the counted value.
KLEMS_FULL_BINS = 145

#: One part in a billion of the assembly's depth. See the module docstring: the man page's own
#: example transform leaves 1.64e-16 of positive Z on a 1.5 m blind, which is ~1e-16 relative.
#: A billionth sits far above that residue and far below any modelled intrusion -- 1.5 nm on a
#: 1.5 m assembly.
HALF_SPACE_RELATIVE_TOLERANCE = 1e-9

#: The floor when the assembly has no depth to scale against (a flat sheet at Z=0, whose Z extent is
#: exactly zero). Without it the relative tolerance collapses to zero and the residue refuses again.
HALF_SPACE_ABSOLUTE_EPSILON = 1e-9

#: Wavelength-band values that mean "one photopic band", i.e. greyscale. `genBSDF -C` writes
#: `Visible`; `Solar` is the other single-band spelling WINDOW files use. Anything else -- a
#: tristimulus or spectral band set -- is colour. Lower-cased for comparison.
_GREYSCALE_BANDS = frozenset({"visible", "solar"})

#: What an `isotropic=True` override is recorded as. Stated as a constant because it goes into
#: provenance and a provenance string that varies by call site is not searchable.
ANISOTROPY_OVERRIDE_REASON = "caller asserted radial symmetry (isotropic=True)"


class BSDFError(Exception):
    """Base for this module's refusals.

    Carries a class-level `code`/`severity`/`field` in the shape `rad_core.weather.EPWError` and
    `rad_engine.project.ProjectError` established, so the protocol layer shapes one advisory from
    the exception rather than re-deriving the classification per call site.
    """

    code: str | None = None
    severity: Literal["error", "warn", "info"] = "error"
    field: str | None = None


class BSDFParseError(BSDFError):
    """The text is not a BSDF XML, or its own structure contradicts itself.

    `code` is deliberately `None`: the advisory register allocates nothing for "these bytes are not
    a BSDF", and the class ruling R14 allocated for an argument refused on its face
    (`ARGUMENT_OUT_OF_RANGE`) is assigned one layer up, exactly as `rad_core.weather.EPWError`
    declines to assign it. `field` names the argument the caller can act on.
    """

    field = "path"


@dataclass(frozen=True)
class Component:
    """One `WavelengthDataBlock`: which hemisphere pair it describes, and what kind of data it is.

    `direction` is the file's own `WavelengthDataDirection` string (`"Transmission Front"`,
    `"Reflection Back"`, ...) rather than a parsed enum, because the WINDOW6 schema admits vendor
    spellings this module has not seen and a value it cannot map is still a value worth reporting.
    """

    direction: str
    scattering_data_type: str | None = None


@dataclass(frozen=True)
class SuitableFor:
    """Which methods a file's basis can be used in. Three independent claims -- see the module
    docstring for the citation behind each."""

    three_phase: bool
    five_phase_direct: bool
    rendering: bool


@dataclass(frozen=True)
class BSDFFile:
    """What `bsdf(action="inspect")` reports, derived entirely from the XML's own structure.

    Every field is *read*, never inferred from a sibling: `bins` is the summed `nPhis`, not a
    constant looked up from `basis_name`, and `has_geometry` is the presence of the element rather
    than a guess from the file's size.
    """

    basis: Basis
    bins: int | None
    basis_name: str | None
    components: tuple[Component, ...]
    band: str | None
    has_geometry: bool
    reciprocity_averaged: bool | None
    """**Always `None`, and the reason is the file format rather than an unfinished parse.**

    `genBSDF`'s `+a`/`-a` controls reciprocity averaging for tensor-tree output, and **nothing in the
    XML records which was used** — verified by scanning both generated fixtures for any tag matching
    `recipro`/`averaged`: neither carries one. `checkBSDF` prints a *"Reciprocity Error (min avg
    max %)"* table, which is a measurement of the data's symmetry and not a record of the flag; the
    Klems fixture shows a 63.8 % maximum on a file whose averaging setting is simply unknown.

    §9's return block names the key, so it is present and typed. It is `None` because this server
    cannot establish it from the file, and reporting `True` on the grounds that `+a` is `genBSDF`'s
    default would be publishing an assumption about a *supplied* WINDOW6 file as if it were read —
    exactly the substituted-default-as-measured-value failure the reporting rules forbid. A future
    phase that generates and records the flag in the manifest can answer it from provenance; reading
    it out of the XML is not possible.
    """
    device_type: str | None
    suitable_for: SuitableFor

    @property
    def is_greyscale(self) -> bool:
        """Whether this file's data is greyscale rather than tristimulus.

        **`band` is not the discriminator, and assuming it was got this wrong.** A `genBSDF -C`
        greyscale file declares `<Wavelength>Visible</Wavelength>` -- measured on the generated
        fixture, where `checkBSDF` independently reports `Color: 0` on the very same file
        (`tests/fixtures/README.md`). So keying the `BSDF_GREYSCALE` advisory on a *missing* band
        never fired it on the exact case it exists to report.

        The real discriminator is the wavelength band's own value: `+C` output carries tristimulus
        data under a colour band, while `-C` collapses everything to the single photopic `Visible`
        band. A file with no band at all is treated as greyscale too -- that is the weaker claim, and
        `BSDF_GREYSCALE` is `info` rather than a refusal precisely because being greyscale is normal
        and correct for illuminance work.
        """
        if self.band is None:
            return True
        return self.band.strip().lower() in _GREYSCALE_BANDS

    @property
    def has_back_component(self) -> bool:
        """Whether any component describes light arriving at the back (exterior) face.

        The condition behind `BSDF_NO_BACK_COMPONENT`: `genBSDF` computes only the backward
        components unless `+forward` is given, and a file missing them is one whose exterior-side
        data is absent rather than zero. Verified on the generated Klems fixture, where `checkBSDF`
        reports `Exterior Refl` and `Ext->Int Trans` at 0.0% / 180 deg -- empty, not measured
        (`tests/fixtures/README.md`).
        """
        return any("front" in component.direction.lower() for component in self.components)


# --- the parse -----------------------------------------------------------------------------------


def _local(tag: str) -> str:
    """A tag's local name, with any `{namespace}` prefix stripped.

    See the module docstring: matching on the local name handles the `{http://windows.lbl.gov}`
    form `genBSDF` writes, a namespace-less hand-written file, and another vendor's namespace,
    identically -- and an un-namespaced `find()` silently matches none of them.
    """
    return tag.rsplit("}", 1)[-1] if "}" in tag else tag


def _findall(root: ElementTree.Element, name: str) -> list[ElementTree.Element]:
    return [element for element in root.iter() if _local(element.tag) == name]


def _first(root: ElementTree.Element, name: str) -> ElementTree.Element | None:
    return next((element for element in root.iter() if _local(element.tag) == name), None)


def _text(root: ElementTree.Element, name: str) -> str | None:
    element = _first(root, name)
    if element is None or element.text is None:
        return None
    stripped = element.text.strip()
    return stripped or None


def parse_bsdf(text: str) -> BSDFFile:
    """Read a BSDF XML's structure from its text. No file handle, no binary, no Radiance.

    Raises `BSDFParseError` when the text is not XML at all, when its root is not a
    `WindowElement`, or when the file's own statements contradict each other -- a declared Klems
    basis whose blocks sum to a different count is not a file this module reports a number for.
    """
    try:
        root = ElementTree.fromstring(text)
    except ElementTree.ParseError as exc:
        raise BSDFParseError(
            f"this file is not well-formed XML and so cannot be a BSDF: {exc}. A BSDF XML is the "
            "LBNL WINDOW6 format that genBSDF and WINDOW write."
        ) from exc

    if _local(root.tag) != "WindowElement":
        raise BSDFParseError(
            f"this XML's root element is {_local(root.tag)!r}, not 'WindowElement', so it is not a "
            "WINDOW6 BSDF file. genBSDF and WINDOW both write a WindowElement root."
        )

    basis_name = _text(root, "AngleBasisName")
    bins = _klems_bins(root, basis_name)
    basis = _basis_of(root, basis_name, bins)
    if basis is Basis.KLEMS and bins is None:
        raise BSDFParseError(
            "this file declares a Klems angle basis but carries no AngleBasisBlock elements to "
            "count directions from, so its bin count cannot be established. A Klems XML written by "
            "genBSDF carries one block per theta ring, each with an nPhis count."
        )

    return BSDFFile(
        basis=basis,
        bins=bins,
        basis_name=basis_name,
        components=_components(root),
        band=_text(root, "Wavelength"),
        has_geometry=_first(root, "Geometry") is not None,
        reciprocity_averaged=None,
        device_type=_text(root, "DeviceType"),
        suitable_for=suitable_for(basis),
    )


def _klems_bins(root: ElementTree.Element, basis_name: str | None) -> int | None:
    """Sum the `nPhis` counts, or `None` when the file carries no angle-basis blocks.

    Counted from the file, never matched off `basis_name` -- see the module docstring. A declared
    full Klems basis whose blocks sum to something other than 145 raises rather than reporting
    either number, because the file's two statements about itself disagree and picking one hides
    the disagreement.
    """
    blocks = _findall(root, "AngleBasisBlock")
    if not blocks:
        return None
    total = 0
    for block in blocks:
        n_phis = _text(block, "nPhis")
        # A block with no nPhis is one direction: the Klems basis's first ring is the normal-incidence
        # patch, and genBSDF writes its nPhis as 1 explicitly. Defaulting to 1 rather than skipping
        # keeps a hand-written file that omits it countable instead of silently short.
        try:
            total += 1 if n_phis is None else int(n_phis)
        except ValueError as exc:
            raise BSDFParseError(
                f"an AngleBasisBlock declares nPhis={n_phis!r}, which is not a whole number of "
                "azimuthal divisions, so this file's direction count cannot be established."
            ) from exc

    if basis_name and "klems full" in basis_name.lower() and total != KLEMS_FULL_BINS:
        raise BSDFParseError(
            f"this file names its basis {basis_name!r} but its {len(blocks)} AngleBasisBlock "
            f"elements sum to {total} directions, not the {KLEMS_FULL_BINS} the full Klems basis "
            "has. The file's own two statements about its basis disagree, so neither is reported."
        )
    return total


def _basis_of(
    root: ElementTree.Element, basis_name: str | None, bins: int | None
) -> Basis:
    """Which of the three bases this file is.

    Decided from *structure*, in one order: a file carrying angle-basis blocks is a fixed-direction
    (Klems) file, and one carrying none is a tensor tree. The rank then comes from the tree's own
    declaration.

    A tensor tree's rank is not always recoverable from the XML -- `genBSDF` writes the tree under a
    single data element and the rank lives in how the tree nests, not in a tag. Where nothing
    declares it, `tensor4` is reported: `-t4` is the mode the man page calls *"suitable for use in
    the Radiance rendering tools"* and `-t3` is the special case a caller opts into, so the general
    mode is the safer report. It also fails safe in the one direction that matters --
    `BSDF_TENSOR_ISOTROPY_ASSUMED` is a warning *about* `-t3`, and reporting a `-t3` file as
    `tensor4` never suppresses a refusal, where the reverse would.
    """
    if bins is not None:
        return Basis.KLEMS
    declared = (_text(root, "AngleBasis") or basis_name or "").lower()
    if "tensor3" in declared or "rank 3" in declared:
        return Basis.TENSOR3
    return Basis.TENSOR4


def _components(root: ElementTree.Element) -> tuple[Component, ...]:
    """Every `WavelengthDataBlock`, in file order.

    File order rather than sorted: the order is the file's own statement about how its data blocks
    are laid out, and a caller comparing two files' component lists is comparing structure.
    """
    components = []
    for block in _findall(root, "WavelengthDataBlock"):
        direction = _text(block, "WavelengthDataDirection")
        if direction is None:
            continue
        components.append(
            Component(
                direction=direction,
                scattering_data_type=_text(block, "ScatteringDataType"),
            )
        )
    return tuple(components)


def suitable_for(basis: Basis) -> SuitableFor:
    """What a basis can be used in. See the module docstring for the citation behind each claim."""
    klems = basis is Basis.KLEMS
    return SuitableFor(
        three_phase=klems,
        five_phase_direct=not klems,
        rendering=True,
    )


# --- the sample-count floor ----------------------------------------------------------------------


#: R749: the `-t3`/`-t4` Nlog2 values `bsdf generate` accepts. 2 is measured: genBSDF exited 25 at
#: `-t4` 1, 0 and -1 and at `-t3` 1 (`-t3` 0 and -1 were not run), and ran at 2 on both bases. 10 is
#: chosen, not measured (docs/tool-surface.md, Unsourced values): its tensor4 floor is
#: 10 * 4**10 = 10,485,760 samples.
RESOLUTION_MIN = 2
RESOLUTION_MAX = 10
#: R749: the `-c` values `bsdf generate` accepts. 1 is from a run and a reading: genBSDF wrote a file
#: for `-c 0` (run), and its own rounding makes 0 one sample (read from the script), so 0 is refused
#: rather than silently run as 1; it died in its own `sqrt` for `-c -1` (run). `-c 1` itself was not
#: run. 2**31 - 1, the largest 32-bit signed integer, is chosen, not measured (Unsourced values); it
#: holds the tensor4 floor at `RESOLUTION_MAX`.
SAMPLES_MIN = 1
SAMPLES_MAX = 2**31 - 1


def sample_floor(basis: Basis, resolution: int | None) -> int:
    """The `-c` floor for a basis, per docs/tool-surface.md#9-bsdf.

    ```
    klems    :  c >= 2000                  # the documented default, per Klems direction
    tensor4  :  c >= 10 * 4^Nlog2          # Nlog2=5 -> 10240,  Nlog2=6 -> 40960
    tensor3  :  c >= 10 * 2^Nlog2          # one fewer dimension sampled
    ```

    A flat "below 2000" threshold is wrong and the spec says why: `genBSDF -t4 6 -c 2000` passes it
    at **0.5 samples per region** -- a valid XML of a device that was never adequately sampled. The
    man page gives the tensor rule directly: *"A -t4 parameter of 5 corresponds to 32x32 or 1024
    output regions, so a -c setting of 10240 would provide 10 samples per region on average.
    Increasing the resolution to 6 corresponds to 64x64 or 4096 regions, so the -c setting would
    need to be increased by a factor of 4"* (verified against `man genBSDF`, Radiance 6.1a).

    `resolution` is required for a tensor basis and ignored for Klems, whose 2000 is per-direction
    over a fixed 145 and does not vary.
    """
    if basis is Basis.KLEMS:
        return 2000
    if resolution is None:
        raise BSDFParseError(
            f"a {basis.value} basis has no sample floor without a resolution: the floor is derived "
            "from the number of output regions, which is set by the -t3/-t4 Nlog2 parameter."
        )
    base = 4 if basis is Basis.TENSOR4 else 2
    return 10 * base**resolution


def samples_per_region(basis: Basis, resolution: int | None, samples: int) -> float | None:
    """Samples per output region -- the number `BSDF_SAMPLE_COUNT_LOW` reports rather than just the
    flag, so a caller sees how far under the floor they are.

    `None` for Klems, whose 2000 is a per-direction count over a fixed basis rather than a density
    over regions: dividing it by 145 would publish a number the man page never defines.
    """
    if basis is Basis.KLEMS or resolution is None:
        return None
    base = 4 if basis is Basis.TENSOR4 else 2
    return samples / base**resolution


# --- the generate preconditions ------------------------------------------------------------------


@dataclass(frozen=True)
class BoundingBox:
    """An axis-aligned box, in the scene's own units. What `getbbox` reports, as data.

    Pure: this module never runs `getbbox`. `rad_engine.bsdf` does, and hands the six numbers here.
    """

    x_min: float
    x_max: float
    y_min: float
    y_max: float
    z_min: float
    z_max: float

    @property
    def depth(self) -> float:
        return self.z_max - self.z_min

    @property
    def width(self) -> float:
        return self.x_max - self.x_min

    @property
    def height(self) -> float:
        return self.y_max - self.y_min


@dataclass(frozen=True)
class GeometryPrecondition:
    """Whether geometry may be handed to `genBSDF`, and every reason it may not.

    `reasons` is a tuple rather than one string because the preconditions are independent: geometry
    can be both in the wrong half-space *and* degenerate, and a caller fixing one wants to know
    about the other before they run a 90-second generation again.
    """

    ok: bool
    reasons: tuple[str, ...] = ()
    z_max_tolerance: float = 0.0
    anisotropic: bool = False
    isotropy_overridden: bool = False
    overridden_reasons: tuple[str, ...] = field(default=())


def check_generate_geometry(
    box: BoundingBox,
    *,
    basis: Basis,
    anisotropic: bool = False,
    isotropic: bool = False,
) -> GeometryPrecondition:
    """Check `genBSDF`'s hard preconditions before a single ray is traced.

    Two independent checks, per docs/tool-surface.md#9-bsdf:

    **The half-space.** The geometry *"should not contain any positive Z values, since the putative
    emitting surface is assumed to lie at Z=0"* (`man genBSDF`). Checked with a scaled tolerance,
    because the man page's own example transform leaves 1.64e-16 of positive Z -- see the module
    docstring, which explains why a bare `z_max > 0` would refuse Radiance's own worked example.

    **The rank-3 isotropy rule.** `basis="tensor3"` on anisotropic geometry is refused: `-t3`
    *"only works ... when the system has a high degree of radial symmetry"*, and a rank-3 tree of a
    venetian blind is fast and wrong. `isotropic=True` honours a caller who knows better and
    records that it happened in `overridden_reasons`, because the failure this refusal prevents is
    invisible in the output.

    `anisotropic` is a *finding*, passed in by whichever layer inspected the geometry, not something
    this function derives from a bounding box -- a box cannot see slats. It is threaded through so
    the two preconditions are answered in one place and one order.
    """
    reasons: list[str] = []
    overridden: list[str] = []

    tolerance = max(
        abs(box.depth) * HALF_SPACE_RELATIVE_TOLERANCE, HALF_SPACE_ABSOLUTE_EPSILON
    )
    if not math.isfinite(box.z_max) or not math.isfinite(box.z_min):
        reasons.append(
            "the geometry's Z extent is not a finite number, so genBSDF's half-space precondition "
            "cannot be checked against it."
        )
    elif box.z_max > tolerance:
        reasons.append(
            f"the geometry reaches Z={box.z_max:g}, which is inside the room. genBSDF requires the "
            "whole assembly in the negative Z half-space with the emitting surface at Z=0 and +Z "
            "pointing into the room, so a positive Z value means the fenestration would be modelled "
            f"protruding through its own aperture. Move it with `xform -t 0 0 {-box.z_max:g}`, or "
            "compose the rotation the man page's own example uses: "
            "`genblinds ... | xform -rz -90 -rx 90`."
        )

    if box.width <= 0.0 or box.height <= 0.0:
        reasons.append(
            f"the geometry's aperture is degenerate ({box.width:g} wide by {box.height:g} high). "
            "genBSDF requires a rectangular profile with width along X and height along Y, so an "
            "assembly flat in either axis has no aperture to emit through."
        )

    if anisotropic and basis is Basis.TENSOR3:
        if isotropic:
            overridden.append(
                "geometry looks anisotropic (distinct parallel surfaces stacked along one axis, "
                f"which is what venetian slats are), but {ANISOTROPY_OVERRIDE_REASON}. A rank-3 "
                "tree of an anisotropic system is fast and wrong, and the error does not show up in "
                "the XML -- this override is recorded in the artifact's provenance for that reason."
            )
        else:
            reasons.append(
                "basis='tensor3' is refused on this geometry: it looks anisotropic, and the "
                "genBSDF man page says 'do NOT use this option if the system is not in fact "
                "isotropic ... only use -t3 when you are certain that the system has a high degree "
                "of radial symmetry'. A rank-3 tree of a venetian blind computes quickly and is "
                "wrong, with nothing in the output to say so. Use basis='tensor4' for this device, "
                "or pass isotropic=True if you are certain it is radially symmetric."
            )

    return GeometryPrecondition(
        ok=not reasons,
        reasons=tuple(reasons),
        z_max_tolerance=tolerance,
        anisotropic=anisotropic,
        isotropy_overridden=bool(overridden),
        overridden_reasons=tuple(overridden),
    )


# --- R871: the Klems diffuse integral and the Lambertian composition ----------------------------

#: R871: the fraction of the open state's diffuse transmittance a blind with no declared closed
#: state transmits, as a uniform (Lambertian) Klems block. LM-83's default closed blind.
LM83_DEFAULT_DIFFUSE_FRACTION: Final[float] = 0.05

#: R871: the visible transmission blocks in the order Radiance's XML matrix loader reads them when a
#: file carries more than one. Measured, not assumed: `rmtxop -fa` (the `cm_loadBTDF` path
#: `dctimestep` takes for an XML operand) on two Lambertian files built from
#: `clear_glazing_klems.xml` -- `Transmission Front` 0.2 / `Transmission Back` 0.6, and the reverse
#: -- sums to 260.92 and 86.97, a ratio of 3.000 (Radiance 6.1a on this install), so the loader
#: reads `Transmission Back` when both are present
#: (`tests/test_bsdf.py::test_the_t_matrix_reads_the_block_klems_t_matrix_directions_names_first`).
KLEMS_T_MATRIX_DIRECTIONS: Final[tuple[str, str]] = ("Transmission Back", "Transmission Front")

_SCATTERING_SPLIT = re.compile(r"[\s,]+")
#: A tag with an optional namespace prefix, for the text splice (no ElementTree round trip: that
#: would rewrite the namespace prefixes Radiance's own reader sees).
_PREFIX = r"(?:[A-Za-z_][\w.-]*:)?"
_WAVELENGTH_DATA_RE = re.compile(
    rf"<{_PREFIX}WavelengthData\b[^>]*>(.*?)</{_PREFIX}WavelengthData\s*>", re.S
)
_WAVELENGTH_RE = re.compile(rf"<{_PREFIX}Wavelength\b[^>]*>(.*?)</{_PREFIX}Wavelength\s*>", re.S)
_DATA_BLOCK_RE = re.compile(
    rf"<{_PREFIX}WavelengthDataBlock\b[^>]*>(.*?)</{_PREFIX}WavelengthDataBlock\s*>", re.S
)
_DIRECTION_RE = re.compile(
    rf"<{_PREFIX}WavelengthDataDirection\b[^>]*>(.*?)</{_PREFIX}WavelengthDataDirection\s*>", re.S
)
_SCATTERING_RE = re.compile(
    rf"<{_PREFIX}ScatteringData\b[^>]*>(.*?)</{_PREFIX}ScatteringData\s*>", re.S
)


@dataclass(frozen=True)
class KlemsRing:
    """One `AngleBasisBlock`: a theta ring from `lower_deg` to `upper_deg`, cut into `n_phis`."""

    lower_deg: float
    upper_deg: float
    n_phis: int


def _xml_root(text: str) -> ElementTree.Element:
    try:
        return ElementTree.fromstring(text)
    except ElementTree.ParseError as exc:
        raise BSDFParseError(
            f"this file is not well-formed XML and so cannot be a BSDF: {exc}."
        ) from exc


def klems_rings(text: str) -> tuple[KlemsRing, ...]:
    """Every `AngleBasisBlock`'s `LowerTheta`, `UpperTheta` and `nPhis`, in file order (R871).

    Refuses a file with no `AngleBasisBlock`, and a ring that is malformed: a bound missing or not
    a finite number, `nPhis` not a positive whole number, `upper <= lower`, or rings that do not
    tile 0 to 90 degrees in order -- the projected solid angles sum to pi only when they do.
    """
    blocks = _findall(_xml_root(text), "AngleBasisBlock")
    if not blocks:
        raise BSDFParseError(
            "this file carries no AngleBasisBlock, so it has no Klems basis to integrate over."
        )
    rings: list[KlemsRing] = []
    for number, block in enumerate(blocks, start=1):
        lower_text, upper_text = _text(block, "LowerTheta"), _text(block, "UpperTheta")
        n_text = _text(block, "nPhis")
        try:
            lower = float(lower_text) if lower_text is not None else math.nan
            upper = float(upper_text) if upper_text is not None else math.nan
            n_phis = 1 if n_text is None else int(n_text)
        except ValueError as exc:
            raise BSDFParseError(
                f"AngleBasisBlock {number} has LowerTheta={lower_text!r}, UpperTheta="
                f"{upper_text!r}, nPhis={n_text!r}, which are not numbers."
            ) from exc
        if not (math.isfinite(lower) and math.isfinite(upper)) or not upper > lower or n_phis < 1:
            raise BSDFParseError(
                f"AngleBasisBlock {number} is malformed: LowerTheta={lower_text!r}, "
                f"UpperTheta={upper_text!r}, nPhis={n_text!r}. A ring needs finite bounds with "
                "UpperTheta above LowerTheta and at least one azimuthal division."
            )
        expected_lower = rings[-1].upper_deg if rings else 0.0
        if not math.isclose(lower, expected_lower, abs_tol=1e-9):
            raise BSDFParseError(
                f"AngleBasisBlock {number} starts at {lower} degrees, not {expected_lower}; the "
                "rings must tile the hemisphere in order for the basis to cover it."
            )
        rings.append(KlemsRing(lower_deg=lower, upper_deg=upper, n_phis=n_phis))
    if not math.isclose(rings[-1].upper_deg, 90.0, abs_tol=1e-9):
        raise BSDFParseError(
            f"the last AngleBasisBlock ends at {rings[-1].upper_deg} degrees, not 90; the basis "
            "does not cover the hemisphere."
        )
    return tuple(rings)


def klems_projected_solid_angles(rings: Sequence[KlemsRing]) -> tuple[float, ...]:
    """One projected solid angle per patch, in basis order (R871).

    Patch `k` in ring `r`: lambda_k = pi (sin^2 upper_r - sin^2 lower_r) / nPhis_r. Over rings that
    tile 0 to 90 degrees they sum to pi.
    """
    lambdas: list[float] = []
    for ring in rings:
        upper = math.sin(math.radians(ring.upper_deg)) ** 2
        lower = math.sin(math.radians(ring.lower_deg)) ** 2
        lambdas.extend([math.pi * (upper - lower) / ring.n_phis] * ring.n_phis)
    return tuple(lambdas)


def klems_transmission_blocks(text: str) -> dict[tuple[str, str], list[list[float]]]:
    """Every `WavelengthDataBlock`'s `ScatteringData`, keyed by `(wavelength, direction)` (R871).

    Reflection blocks included, despite the name: the key's direction says which it is. Each value
    is `bins` rows of `bins` values in file order, `bins` the sum of the file's `nPhis`. Refuses a
    block whose value count is not `bins * bins`, a token that is not a number, a block with no
    wavelength or direction, and a repeated key.
    """
    root = _xml_root(text)
    bins = sum(ring.n_phis for ring in klems_rings(text))
    blocks: dict[tuple[str, str], list[list[float]]] = {}
    for data in _findall(root, "WavelengthData"):
        wavelength = _text(data, "Wavelength")
        for block in _findall(data, "WavelengthDataBlock"):
            direction = _text(block, "WavelengthDataDirection")
            if wavelength is None or direction is None:
                raise BSDFParseError(
                    "a WavelengthDataBlock has no Wavelength or no WavelengthDataDirection, so "
                    "which data it is cannot be established."
                )
            key = (wavelength, direction)
            if key in blocks:
                raise BSDFParseError(f"the file carries two {key!r} blocks; neither is chosen.")
            scattering = _first(block, "ScatteringData")
            raw = scattering.text if scattering is not None and scattering.text else ""
            try:
                values = [float(token) for token in _SCATTERING_SPLIT.split(raw) if token]
            except ValueError as exc:
                raise BSDFParseError(
                    f"the {key!r} block carries a value that is not a number: {exc}"
                ) from exc
            if len(values) != bins * bins:
                raise BSDFParseError(
                    f"the {key!r} block carries {len(values)} values, not the {bins} x {bins} = "
                    f"{bins * bins} its basis needs."
                )
            blocks[key] = [values[row * bins : (row + 1) * bins] for row in range(bins)]
    return blocks


def klems_diffuse_transmittance(
    matrix: Sequence[Sequence[float]], lambdas: Sequence[float]
) -> float:
    """The diffuse-diffuse (hemispherical) transmittance of a Klems block (R871).

    tau = (1/pi) sum_i lambda_i sum_o T[o][i] lambda_o. Symmetric in `o` and `i`, so the file's
    `IncidentDataStructure` (rows or columns) does not change it.
    """
    n = len(lambdas)
    if len(matrix) != n or any(len(row) != n for row in matrix):
        raise BSDFParseError(
            f"the block is not {n} x {n}, the size of the basis it is integrated over."
        )
    return math.fsum(
        lambdas[o] * math.fsum(value * lambdas[i] for i, value in enumerate(row))
        for o, row in enumerate(matrix)
    ) / math.pi


def lambertian_klems_text(open_text: str, *, fraction: float) -> tuple[str, float, float]:
    """The open state's Klems file with every transmission block made uniform (R871).

    Each transmission block (`WavelengthDataDirection` starting `Transmission`) becomes 145 x 145
    copies of `fraction * tau_block / pi`, `tau_block` that block's own integral (a Solar block
    scales by its own, a Visible block by its own). Everything else -- the header, the
    `DataDefinition`, the reflection blocks -- is kept byte for byte: a text splice inside each
    matched `WavelengthDataBlock`, no ElementTree round trip.

    Returns the composed text, the open state's visible diffuse-diffuse transmittance `tau` (from
    the first of `KLEMS_T_MATRIX_DIRECTIONS` the file carries) and `fraction * tau`.

    Refuses (`BSDFParseError`) a file that is not Klems full, one with no Visible transmission
    block, a block whose value count is not 145 x 145, a non-finite or negative value, and its own
    output if the re-parsed visible integral is not `fraction * tau` within 1e-8 relative.
    """
    if not (math.isfinite(fraction) and 0.0 <= fraction <= 1.0):
        raise BSDFParseError(f"fraction must be a finite number from 0 to 1, not {fraction!r}.")
    info = parse_bsdf(open_text)
    if info.basis is not Basis.KLEMS or info.bins != KLEMS_FULL_BINS:
        raise BSDFParseError(
            f"a Lambertian state is composed from a full Klems file ({KLEMS_FULL_BINS} bins); this "
            f"file's basis is {info.basis.value} with {info.bins} bins."
        )
    blocks = klems_transmission_blocks(open_text)
    lambdas = klems_projected_solid_angles(klems_rings(open_text))
    chain = next((d for d in KLEMS_T_MATRIX_DIRECTIONS if ("Visible", d) in blocks), None)
    if chain is None:
        raise BSDFParseError(
            "this file carries no Visible transmission block (neither "
            f"{' nor '.join(repr(d) for d in KLEMS_T_MATRIX_DIRECTIONS)}), so it has no visible "
            "transmittance to take a fraction of."
        )
    replacements: dict[tuple[str, str], str] = {}
    for key, block in blocks.items():
        if not key[1].startswith("Transmission"):
            continue
        for row in block:
            for value in row:
                if not math.isfinite(value) or value < 0:
                    raise BSDFParseError(
                        f"the {key!r} block carries {value!r}; a transmission value is finite and "
                        "non-negative."
                    )
        uniform = fraction * klems_diffuse_transmittance(block, lambdas) / math.pi
        line = " ".join([f"{uniform:.9e}"] * KLEMS_FULL_BINS)
        replacements[key] = "\n" + "\n".join([line] * KLEMS_FULL_BINS) + "\n"
    tau_open = klems_diffuse_transmittance(blocks[("Visible", chain)], lambdas)
    tau_closed = fraction * tau_open

    pieces: list[str] = []
    cursor = 0
    seen: list[tuple[str, str]] = []
    for data in _WAVELENGTH_DATA_RE.finditer(open_text):
        wavelength_match = _WAVELENGTH_RE.search(data.group(1))
        wavelength = wavelength_match.group(1).strip() if wavelength_match else ""
        for block in _DATA_BLOCK_RE.finditer(open_text, data.start(1), data.end(1)):
            direction_match = _DIRECTION_RE.search(block.group(1))
            key = (wavelength, direction_match.group(1).strip() if direction_match else "")
            seen.append(key)
            if key not in replacements:
                continue
            scattering = _SCATTERING_RE.search(open_text, block.start(1), block.end(1))
            if scattering is None:
                raise BSDFParseError(f"the {key!r} block's ScatteringData could not be located.")
            pieces.append(open_text[cursor : scattering.start(1)])
            pieces.append(replacements[key])
            cursor = scattering.end(1)
    pieces.append(open_text[cursor:])
    if seen != list(blocks):
        raise BSDFParseError(
            "the text splice found the data blocks as "
            f"{seen!r} where the XML parse found {list(blocks)!r}; the file is not composed."
        )
    composed = "".join(pieces)

    check = klems_diffuse_transmittance(
        klems_transmission_blocks(composed)[("Visible", chain)], lambdas
    )
    if abs(check - tau_closed) > 1e-8 * abs(tau_closed):
        raise BSDFParseError(
            f"the composed file's visible transmittance reads {check!r}, not {tau_closed!r}; it is "
            "not returned."
        )
    return composed, tau_open, tau_closed
